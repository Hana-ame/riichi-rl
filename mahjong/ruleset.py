def _build_table():
    t = {}
    for fu, row in _TABLE_ROWS.items():
        for han, (dl, nd) in enumerate(row, start=1):
            t[(fu, han)] = (dl, nd)
    return t


#: (fu, han) -> (庄家收点数, 子家收点数)
TABLE = _build_table()


def han_fu_points(fu, han, is_dealer):
    """返回和了方总共收的点数（不含跳满以上）。"""
    dl, nd = TABLE[(fu, han)]
    return dl if is_dealer else nd


# --- 跳满以上 ---
#: 役满倍数 -> 和了方总收点数。8 = 逆满（不流动）
